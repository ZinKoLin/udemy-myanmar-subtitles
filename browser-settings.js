(() => {
  const provider = document.querySelector('#translation-provider');
  const api = document.querySelector('#api-settings');
  const hint = document.querySelector('#browser-hint');
  async function load() {
    const saved = await chrome.storage.local.get(['translationProvider', 'geminiAccountIndex', 'geminiAccountEmail', 'geminiBrowserModel', 'n8nUrl', 'n8nToken']);
    provider.value = ['api', 'n8n'].includes(saved.translationProvider) ? saved.translationProvider : 'browser';
    document.querySelector('#n8n-url').value = saved.n8nUrl || '';
    document.querySelector('#n8n-token').value = saved.n8nToken || '';
    document.querySelector('#gemini-account-index').value = saved.geminiAccountIndex ?? 2;
    document.querySelector('#gemini-account-email').value = saved.geminiAccountEmail || '';
    document.querySelector('#browser-model').value = saved.geminiBrowserModel || 'hydrogen-medium';
    update();
  }
  function update() { document.querySelector('#browser-model-settings').hidden = provider.value === 'api'; api.hidden = provider.value !== 'api'; hint.hidden = provider.value !== 'browser'; document.querySelector('#n8n-hint').hidden = provider.value !== 'n8n'; document.querySelector('#provider-status').hidden = provider.value !== 'api'; }
  document.querySelector('#n8n-settings').addEventListener('submit', async event => {
    event.preventDefault();
    try {
      const target = new URL(document.querySelector('#n8n-url').value.trim());
      if ((target.protocol !== 'https:' && !(target.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(target.hostname))) || target.username || target.password || target.hash || target.search) throw new Error('Use an HTTPS webhook URL (or localhost through an SSH tunnel), without credentials or query parameters.');
      const n8nToken = document.querySelector('#n8n-token').value.trim();
      if (n8nToken.length < 32 || /[\r\n]/.test(n8nToken)) throw new Error('Enter the webhook token generated by the server setup (at least 32 characters).');
      const granted = await chrome.permissions.request({ origins: [target.origin + '/*'] });
      if (!granted) throw new Error('Access to the n8n host was not granted.');
      await chrome.storage.local.set({ n8nUrl: target.href, n8nToken, translationProvider: 'n8n' });
      provider.value = 'n8n'; update();
      document.querySelector('#status').textContent = 'n8n connection saved. Reload Udemy or select n8n in the lecture panel. Server installation and Gemini login are required.';
    } catch (error) { document.querySelector('#status').textContent = error.message; }
  });
  document.querySelector('#browser-account-settings').addEventListener('submit', async event => {
    event.preventDefault();
    const geminiAccountIndex = Number(document.querySelector('#gemini-account-index').value);
    const geminiAccountEmail = document.querySelector('#gemini-account-email').value.trim().toLowerCase();
    try {
      if (!Number.isInteger(geminiAccountIndex) || geminiAccountIndex < 0 || geminiAccountIndex > 20 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(geminiAccountEmail)) throw new Error('Enter the account number and email shown in your Pro Gemini tab.');
      await chrome.storage.local.set({ geminiAccountIndex, geminiAccountEmail, translationProvider: 'browser' });
      provider.value = 'browser'; update();
      document.querySelector('#status').textContent = 'Pro အကောင့် သိမ်းပြီးပါပြီ။ ရွေးထားသော model ဖြင့် သုံးရန် Udemy မှာ Translate နှိပ်ပါ။';
    } catch (error) { document.querySelector('#status').textContent = error.message; }
  });
  document.querySelector('#browser-model').addEventListener('change', async event => {
    try {
      await chrome.storage.local.set({ geminiBrowserModel: event.target.value });
      document.querySelector('#status').textContent = 'Model သိမ်းပြီးပါပြီ။ Udemy မှာ Translate ပြန်နှိပ်ပါ။';
    } catch (error) { document.querySelector('#status').textContent = error.message; }
  });
  provider.addEventListener('change', async () => {
    update();
    await chrome.storage.local.set({ translationProvider: provider.value });
    document.querySelector('#status').textContent = provider.value === 'browser' ? 'Gemini browser selected. No API key needed. Reload the Udemy lecture.' : provider.value === 'n8n' ? 'n8n server selected. Configure the connection below before translating.' : 'Gemini API selected. Reload the Udemy lecture.';
    try { const [tab] = await chrome.tabs.query({ active: true, currentWindow: true }); await chrome.tabs.sendMessage(tab.id, { type: 'MODEL_CHANGED' }); } catch {}
  });
  load().catch(() => { document.querySelector('#status').textContent = 'Could not load translation method.'; });
})();
